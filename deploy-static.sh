#!/usr/bin/env bash
# Assemble only public static assets. Does not upload code, credentials, or accounts.
set -euo pipefail
TASK_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_DIR="$TASK_ROOT/github-pages"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --out)
      [[ $# -ge 2 && -n "$2" ]] || { echo '缺少 --out 資料夾。' >&2; exit 2; }
      OUTPUT_DIR="$2"; shift 2;;
    -h|--help)
      echo '使用：bash deploy-static.sh [--out 輸出資料夾]'
      echo '預設輸出 github-pages/；產生 GitHub Pages 可直接發布的純靜態網站。'
      echo '重複匯出只允許覆寫本腳本標記的生成目錄，不覆寫其他既有資料夾。'
      exit 0;;
    *) echo "未知選項：$1" >&2; exit 2;;
  esac
done
command -v python3 >/dev/null || { echo '需要 Python 3.10 或更新版本。' >&2; exit 1; }
bash "$TASK_ROOT/build-offline.sh" --if-needed
python3 - "$TASK_ROOT" "$OUTPUT_DIR" <<'PY'
import pathlib, shutil, sys, tempfile
root = pathlib.Path(sys.argv[1]).resolve()
output = pathlib.Path(sys.argv[2]).resolve()
source = root / 'public' / 'academy'
if not source.is_dir():
    source = root / 'portable' / 'public'
required = ['index.html','bootstrap.js','app.bundle.js','offline-data.js','offline-runtime.js','offline-build.json','app.js','style.css','data/lazy/index.json','data/catalog.json','data/featured.json','data/sources.json','data/photos.json']
missing = [p for p in required if not (source/p).is_file()]
if missing:
    sys.exit('靜態素材尚未完整，缺少：' + ', '.join(missing))
if output == root or output == source or output in source.parents or source in output.parents:
    sys.exit('輸出目錄不可為專案根目錄、來源或來源的上下層。')
marker = '.macgyver-static-export'
if output.exists() and not (output/marker).is_file():
    sys.exit('輸出目錄已存在且非本腳本產生；請改用新目錄，避免覆寫檔案。')
output.parent.mkdir(parents=True, exist_ok=True)
temporary = pathlib.Path(tempfile.mkdtemp(prefix='macgyver-export-', dir=output.parent))
try:
    shutil.copytree(source, temporary, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('.env*','.git','__pycache__','*.pyc','*.sqlite*','*.pem','*.key'))
    (temporary/'.nojekyll').write_text('',encoding='utf-8')
    (temporary/'runtime-mode.js').write_text('window.MG_STATIC_MODE = true;\n',encoding='utf-8')
    (temporary/marker).write_text('Generated by deploy-static.sh\n',encoding='utf-8')
    # Existing output is generated-only and explicitly marked above.
    if output.exists():
        shutil.rmtree(output)
    temporary.replace(output)
finally:
    if temporary.exists():
        shutil.rmtree(temporary)
print('靜態網站已完成：' + str(output))
print('GitHub Pages 可讀取教材、保存本機進度及選用瀏覽器 CPU AI；跨裝置帳號需設定 Supabase，外部 AI API 需後端代理。')
PY
