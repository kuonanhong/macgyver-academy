#!/usr/bin/env node
/** Dependency-free bundler for this app's relative named-import ES modules.
 * Preserves module scopes and shared exports; fails on unsupported syntax/cycles.
 * End users run the emitted classic scripts, not this build tool.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { restoreFeatured } from './restore-featured.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicRoot = path.join(root, 'public/academy');
restoreFeatured(root,{normalize:true});
const manifestPath = path.join(publicRoot, 'offline-build.json');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const relative = file => path.relative(root, file).split(path.sep).join('/');
const generated = new Set(['app.bundle.js', 'offline-data.js']);
// Weekly-refreshed data is fetched at runtime and must not invalidate the offline bundle.
const volatileData = new Set(['markets.json', 'fx.json']);
const args = new Set(process.argv.slice(2));
if ([...args].some(a => !['--check', '--if-needed'].includes(a))) throw new Error('Use --check or --if-needed.');

function inputs() {
  const result = {};
  const files = [fileURLToPath(import.meta.url), path.join(root,'tools/restore-featured.mjs'), ...fs.readdirSync(publicRoot).filter(n => /\.(js|css|html)$/.test(n) && !generated.has(n) && !/^offline-data-\d+\.js$/.test(n)).map(n => path.join(publicRoot, n)), ...fs.readdirSync(path.join(publicRoot, 'data')).filter(n => n.endsWith('.json') && !volatileData.has(n)).map(n => path.join(publicRoot, 'data', n))];
  for (const file of files.sort()) result[relative(file)] = hash(fs.readFileSync(file));
  return result;
}
const currentInputs = inputs();
function fresh() {
  try {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    return manifest.version === 1 && JSON.stringify(manifest.inputs) === JSON.stringify(currentInputs) && Object.entries(manifest.outputs).every(([name, digest]) => hash(fs.readFileSync(path.join(root, name))) === digest);
  } catch { return false; }
}
if (args.has('--check')) {
  if (!fresh()) { console.error('Offline bundle is stale. Run bash build-offline.sh.'); process.exit(1); }
  console.log('Offline bundle matches every current public JS, CSS, HTML and JSON source.'); process.exit(0);
}
if (args.has('--if-needed') && fresh()) { console.log('Offline bundle is current.'); process.exit(0); }

const modules = new Map(), visiting = new Set();
function named(value) {
  return value.split(',').map(v => v.trim()).filter(Boolean).map(part => {
    const match = part.match(/^([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?$/);
    if (!match) throw new Error(`Unsupported named import/export: ${part}`);
    return [match[1], match[2] || match[1]];
  });
}
function bundleModule(file) {
  file = path.resolve(file);
  if (!file.startsWith(publicRoot + path.sep)) throw new Error('The offline bundle only accepts local public app modules.');
  const id = path.relative(publicRoot, file).split(path.sep).join('/');
  if (visiting.has(id)) throw new Error(`Cyclic imports require an ES-module-aware bundler: ${id}`);
  if (modules.has(id)) return id;
  visiting.add(id);
  let source = fs.readFileSync(file, 'utf8');
  const exports = new Map();
  source = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]\s*;\s*$/gm, (_, names, target) => {
    if (!target.startsWith('./') && !target.startsWith('../')) throw new Error(`Non-local import in ${id}: ${target}`);
    const dependency = bundleModule(path.resolve(path.dirname(file), target));
    return `const { ${named(names).map(([original, local]) => original === local ? original : `${original}: ${local}`).join(', ')} } = require(${JSON.stringify(dependency)});`;
  });
  source = source.replace(/^export\s*\{([^}]+)\}\s*;\s*$/gm, (_, names) => {
    for (const [local, exported] of named(names)) exports.set(exported, local);
    return '';
  });
  source = source.replace(/^export\s+((?:async\s+)?(?:function|class)|const|let|var)\s+([A-Za-z_$][\w$]*)/gm, (_, type, name) => {
    exports.set(name, name); return `${type} ${name}`;
  });
  const exposed = [...exports].map(([name, local]) => `Object.defineProperty(exports, ${JSON.stringify(name)}, { enumerable: true, get: () => ${local} });`).join('\n');
  const wrapped = `function(require, exports) {\n'use strict';\n${source}\n${exposed}\n}`;
  try { new vm.Script(`(${wrapped})`, { filename: id }); }
  catch (error) { throw new Error(`${id}: unsupported module syntax or JavaScript error. ${error.message}`); }
  modules.set(id, wrapped); visiting.delete(id); return id;
}
const entry = bundleModule(path.join(publicRoot, 'app.js'));
const bundle = `/* Generated by tools/build-offline.mjs. Edit source modules and rebuild. */\n(function(){\n'use strict';\nconst factories={\n${[...modules].map(([id, source]) => `${JSON.stringify(id)}:${source}`).join(',\n')}\n};\nconst cache=Object.create(null);\nfunction require(id){if(cache[id])return cache[id];if(!factories[id])throw new Error('Missing bundled module '+id);const exports=cache[id]=Object.create(null);factories[id](require,exports);return exports;}\nrequire(${JSON.stringify(entry)});\n})();\n`;
new vm.Script(bundle, { filename: 'app.bundle.js' });
const data = Object.create(null);
for (const file of fs.readdirSync(path.join(publicRoot, 'data')).filter(n => n.endsWith('.json') && !volatileData.has(n)).sort()) data[file.slice(0, -5)] = JSON.parse(fs.readFileSync(path.join(publicRoot, 'data', file), 'utf8'));
const serialize = value => JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
// Bound individual script size as curricula grow. Classic scripts retain file://
// support; no fetch, decompression API, module worker or CDN is needed.
const parts=[];let batch=[],bytes=0;
for(const course of data.featured){
  const length=Buffer.byteLength(serialize(course));
  if(length>7*1024*1024)throw new Error(`Course ${course.id} exceeds the offline part budget.`);
  if(batch.length&&bytes+length+batch.length+512>7*1024*1024){parts.push(batch);batch=[];bytes=0;}
  batch.push(course);bytes+=length;
}
if(batch.length)parts.push(batch);
const partNames=parts.map((_,i)=>`offline-data-${String(i+1).padStart(2,'0')}.js`);
const preload = `/* Generated public curriculum only. No private documents or model weights. */\nwindow.MG_DATA=${serialize({...data,featured:[]})};\nwindow.MG_DATA_FILES=${serialize(partNames)};\n`;
new vm.Script(preload, { filename: 'offline-data.js' });
function write(file, value) { const temp = `${file}.tmp`; fs.writeFileSync(temp, value); fs.renameSync(temp, file); }
write(path.join(publicRoot, 'app.bundle.js'), bundle);
write(path.join(publicRoot, 'offline-data.js'), preload);
for(let i=0;i<parts.length;i++){
  const code=`/* Generated course part ${i+1}/${parts.length}. */\nwindow.MG_DATA.featured.push(...${serialize(parts[i])});\n`;
  new vm.Script(code,{filename:partNames[i]});
  write(path.join(publicRoot,partNames[i]),code);generated.add(partNames[i]);
}
for(const name of fs.readdirSync(publicRoot).filter(n=>/^offline-data-\d+\.js$/.test(n)&&!generated.has(n)))fs.unlinkSync(path.join(publicRoot,name));
// HTTP clients load the same ordered courses from bounded, immutable JSON
// parts. Keep featured.json as canonical authoring and portable-package data.
const hostedDir = path.join(publicRoot, 'data/course-parts');
fs.mkdirSync(hostedDir, { recursive: true });
const hostedParts = parts.map((courses, index) => {
  const content = JSON.stringify(courses) + '\n';
  const sha256 = hash(content), file = `part-${String(index + 1).padStart(4, '0')}-${sha256.slice(0,16)}.json`;
  const byteLength = Buffer.byteLength(content);
  if (byteLength > 7 * 1024 * 1024) throw new Error(`Hosted curriculum part ${index + 1} exceeds its budget.`);
  write(path.join(hostedDir, file), content);
  return { file, byteLength, sha256, courseCount: courses.length, courseIds: courses.map(course => course.id) };
});
const hostedManifest = { schemaVersion: 1, dataSet: 'featured', courseCount: data.featured.length, parts: hostedParts };
write(path.join(hostedDir, 'index.json'), JSON.stringify(hostedManifest, null, 2) + '\n');
const hostedFiles = new Set(['index.json', ...hostedParts.map(part => part.file)]);
for (const name of fs.readdirSync(hostedDir)) {
  if (/^part-\d{4}-[a-f0-9]{16}\.json$/.test(name) && !hostedFiles.has(name)) fs.unlinkSync(path.join(hostedDir, name));
}
for (const name of hostedFiles) generated.add(`data/course-parts/${name}`);
const outputs = Object.fromEntries([...generated].map(name => [relative(path.join(publicRoot, name)), hash(fs.readFileSync(path.join(publicRoot, name)))]));
write(manifestPath, JSON.stringify({ version: 1, dataSets: Object.keys(data), offlineParts:partNames, modules: [...modules.keys()], inputs: currentInputs, outputs }, null, 2) + '\n');
console.log(`Offline bundle built: ${modules.size} modules, ${Object.keys(data).length} complete JSON data sets, ${parts.length} bounded course parts; no npm dependencies required.`);
