#!/usr/bin/env node
/** Dependency-free bundler for this app's relative named-import ES modules.
 * Preserves module scopes and shared exports; fails on unsupported syntax/cycles.
 * End users run the emitted classic scripts, not this build tool.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { restoreFeatured } from './restore-featured.mjs';
import { expandLazyIndex } from '../public/academy/lazy-index-codec.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicRoot = path.join(root, 'public/academy');
restoreFeatured(root,{normalize:true});
const manifestPath = path.join(publicRoot, 'offline-build.json');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const relative = file => path.relative(root, file).split(path.sep).join('/');
const generated = new Set(['app.bundle.js', 'offline-data.js']);
// Weekly-refreshed data is fetched at runtime and must not invalidate the offline bundle.
const volatileData = new Set(['markets.json', 'fx.json']);
const args = new Set(process.argv.slice(2));
if ([...args].some(a => !['--check', '--if-needed'].includes(a))) throw new Error('Use --check or --if-needed.');

function inputs() {
  const result = {};
  const files = [fileURLToPath(import.meta.url), path.join(root,'tools/restore-featured.mjs'), ...fs.readdirSync(publicRoot).filter(n => /\.(js|css|html)$/.test(n) && !generated.has(n) && !/^offline-data-\d+\.js$/.test(n)).map(n => path.join(publicRoot, n)), ...fs.readdirSync(path.join(publicRoot, 'data')).filter(n => n.endsWith('.json') && !volatileData.has(n)).map(n => path.join(publicRoot, 'data', n))];
  for (const file of files.sort()) result[relative(file)] = hash(fs.readFileSync(file));
  return result;
}
const currentInputs = inputs();
function fresh() {
  try {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    return manifest.version === 1 && manifest.lazyVersion === 1 && JSON.stringify(manifest.inputs) === JSON.stringify(currentInputs) && Object.entries(manifest.outputs).every(([name, digest]) => hash(fs.readFileSync(path.join(root, name))) === digest);
  } catch { return false; }
}
if (args.has('--check')) {
  if (!fresh()) { console.error('Offline bundle is stale. Run bash build-offline.sh.'); process.exit(1); }
  console.log('Offline bundle matches every current public JS, CSS, HTML and JSON source.'); process.exit(0);
}
if (args.has('--if-needed') && fresh()) { console.log('Offline bundle is current.'); process.exit(0); }

const modules = new Map(), visiting = new Set();
function named(value) {
  return value.split(',').map(v => v.trim()).filter(Boolean).map(part => {
    const match = part.match(/^([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?$/);
    if (!match) throw new Error(`Unsupported named import/export: ${part}`);
    return [match[1], match[2] || match[1]];
  });
}
function bundleModule(file) {
  file = path.resolve(file);
  if (!file.startsWith(publicRoot + path.sep)) throw new Error('The offline bundle only accepts local public app modules.');
  const id = path.relative(publicRoot, file).split(path.sep).join('/');
  if (visiting.has(id)) throw new Error(`Cyclic imports require an ES-module-aware bundler: ${id}`);
  if (modules.has(id)) return id;
  visiting.add(id);
  let source = fs.readFileSync(file, 'utf8');
  const exports = new Map();
  source = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]\s*;\s*$/gm, (_, names, target) => {
    if (!target.startsWith('./') && !target.startsWith('../')) throw new Error(`Non-local import in ${id}: ${target}`);
    const dependency = bundleModule(path.resolve(path.dirname(file), target));
    return `const { ${named(names).map(([original, local]) => original === local ? original : `${original}: ${local}`).join(', ')} } = require(${JSON.stringify(dependency)});`;
  });
  source = source.replace(/^export\s*\{([^}]+)\}\s*;\s*$/gm, (_, names) => {
    for (const [local, exported] of named(names)) exports.set(exported, local);
    return '';
  });
  source = source.replace(/^export\s+((?:async\s+)?(?:function|class)|const|let|var)\s+([A-Za-z_$][\w$]*)/gm, (_, type, name) => {
    exports.set(name, name); return `${type} ${name}`;
  });
  const exposed = [...exports].map(([name, local]) => `Object.defineProperty(exports, ${JSON.stringify(name)}, { enumerable: true, get: () => ${local} });`).join('\n');
  const wrapped = `function(require, exports) {\n'use strict';\n${source}\n${exposed}\n}`;
  try { new vm.Script(`(${wrapped})`, { filename: id }); }
  catch (error) { throw new Error(`${id}: unsupported module syntax or JavaScript error. ${error.message}`); }
  modules.set(id, wrapped); visiting.delete(id); return id;
}
const entry = bundleModule(path.join(publicRoot, 'app.js'));
const bundle = `/* Generated by tools/build-offline.mjs. Edit source modules and rebuild. */\n(function(){\n'use strict';\nconst factories={\n${[...modules].map(([id, source]) => `${JSON.stringify(id)}:${source}`).join(',\n')}\n};\nconst cache=Object.create(null);\nfunction require(id){if(cache[id])return cache[id];if(!factories[id])throw new Error('Missing bundled module '+id);const exports=cache[id]=Object.create(null);factories[id](require,exports);return exports;}\nrequire(${JSON.stringify(entry)});\n})();\n`;
new vm.Script(bundle, { filename: 'app.bundle.js' });
const data = Object.create(null);
for (const file of fs.readdirSync(path.join(publicRoot, 'data')).filter(n => n.endsWith('.json') && !volatileData.has(n)).sort()) data[file.slice(0, -5)] = JSON.parse(fs.readFileSync(path.join(publicRoot, 'data', file), 'utf8'));
const serialize = value => JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
// Bound individual script size as curricula grow. Classic scripts retain file://
// support; no fetch, decompression API, module worker or CDN is needed.
const parts=[];let batch=[],bytes=0;
for(const course of data.featured){
  const length=Buffer.byteLength(serialize(course));
  if(length>7*1024*1024)throw new Error(`Course ${course.id} exceeds the offline part budget.`);
  if(batch.length&&bytes+length+batch.length+512>7*1024*1024){parts.push(batch);batch=[];bytes=0;}
  batch.push(course);bytes+=length;
}
if(batch.length)parts.push(batch);
function write(file, value) { const temp = `${file}.tmp`; fs.mkdirSync(path.dirname(file),{recursive:true}); fs.writeFileSync(temp, value); fs.renameSync(temp, file); }
write(path.join(publicRoot, 'app.bundle.js'), bundle);
// Only catalogue metadata and step IDs are required for home, filters and saved
// progress. Lesson bodies and supporting material live in immutable single-course files.
const lazyRoot=path.join(publicRoot,'data/lazy');
const metadataKeys=['id','title','titleEn','category','subcategory','subcategoryTitle','subcategoryTitleEn','summary','summaryEn','status','kind','stepCount','estimatedMinutes','diagram','flowDiagram','photoId','educationEdition','enrichmentVersion','curriculumVersion','contentStatus','depth','languageCoverage','learningTrack','learningSubdiscipline','learningTags','tags','architectureFamily','architectureNodes','architectureEdges'];
const metadata=c=>{
  const result=Object.fromEntries(metadataKeys.filter(k=>c[k]!==undefined).map(k=>[k,c[k]]));
  if(Array.isArray(c.stages)){result._lazy=true;result.stages=c.stages.map(s=>({id:s.id,title:s.title,titleEn:s.titleEn,order:s.order,steps:s.steps.map(step=>({id:step.id}))}));}
  else result._lazyTopic=true;
  return result;
};
const guided=new Map(data.featured.map(c=>[c.id,c]));
const fullCatalog=data.catalog.map(c=>guided.get(c.id)||c);
function chunk(group,id,value){
  if(!/^[a-z0-9]+(?:[-_][a-z0-9]+)*$/.test(id))throw Error('Unsafe lazy data ID: '+id);
  const content=JSON.stringify(value)+'\n',sha256=hash(content),name=`data/lazy/${group}/${id}-${sha256.slice(0,16)}.json`,script=name.replace(/\.json$/,'.js');
  const code=`/* Generated on-demand data. */\nwindow.MG_LAZY_DATA=window.MG_LAZY_DATA||Object.create(null);\nwindow.MG_LAZY_DATA[${JSON.stringify(name)}]={sha256:${JSON.stringify(sha256)},value:${serialize(value)}};\n`;
  write(path.join(publicRoot,name),content);write(path.join(publicRoot,script),code);
  generated.add(name);generated.add(script);
  return {file:name,script,sha256,byteLength:Buffer.byteLength(content)};
}
const sourcesById=new Map(data.sources.map(s=>[s.id,s]));
const byCourse=name=>new Map((data[name]?.courses||[]).map(c=>[c.courseId,c]));
const mediaById=byCourse('media'),relatedById=byCourse('related-skills'),placesById=byCourse('course-places'),vendorsByCourse=byCourse('vendors');
const vendorsById=new Map((data.vendors?.vendors||[]).map(v=>[v.id,v]));
const courseFiles={},resourceFiles={};
for(const c of fullCatalog){
  courseFiles[c.id]=chunk('courses',c.id,c);
  const sourceIds=new Set(c.sourceIds||[]);
  for(const stage of c.stages||[]){for(const id of stage.sourceIds||[])sourceIds.add(id);for(const step of stage.steps||[]){for(const id of step.sourceIds||[])sourceIds.add(id);for(const k of step.knowledge||[])for(const id of k.sourceIds||[])sourceIds.add(id);}}
  const association=vendorsByCourse.get(c.id);
  resourceFiles[c.id]=chunk('resources',c.id,{sources:[...sourceIds].map(id=>sourcesById.get(id)).filter(Boolean),media:{courses:[mediaById.get(c.id)].filter(Boolean)},related:{courses:[relatedById.get(c.id)].filter(Boolean)},places:{courses:[placesById.get(c.id)].filter(Boolean)},vendors:{courses:[association].filter(Boolean),vendors:(association?.vendorIds||[]).map(id=>vendorsById.get(id)).filter(Boolean)}});
}
const sourceUsage=data.featured.map(c=>({
  ...metadata(c),sourceIds:c.sourceIds||[],
  stages:c.stages.map(stage=>({
    sourceIds:stage.sourceIds||[],
    steps:stage.steps.map(step=>({id:step.id,sourceIds:step.sourceIds||[],photoId:step.photoId,knowledge:(step.knowledge||[]).map(k=>({sourceIds:k.sourceIds||[]}))}))
  }))
}));
const auxiliary={};
for(const [name,value] of Object.entries({...data,'source-usage':sourceUsage}))if(!['catalog','featured','photos','release'].includes(name))auxiliary[name]=chunk('data',name,value);
const index={lazyVersion:1,guidedIds:data.featured.map(c=>c.id),catalog:fullCatalog.map(metadata),photos:data.photos,release:data.release,courses:courseFiles,resources:resourceFiles,auxiliary};
const indexName='data/lazy/index.json';write(path.join(publicRoot,indexName),JSON.stringify(index)+'\n');generated.add(indexName);
// Lossless wire compaction removes repeated descriptor paths and step-object keys.
// Keep the expanded index for diagnostics and older integration tooling.
const compactDescriptors=entries=>Object.fromEntries(Object.entries(entries).map(([id,d])=>[id,[d.sha256,d.byteLength]]));
const compactIndex={...index,compactVersion:1,catalog:index.catalog.map(c=>c.stages?{...c,stages:c.stages.map(s=>({...s,steps:s.steps.map(step=>step.id)}))}:c),courses:compactDescriptors(index.courses),resources:compactDescriptors(index.resources),auxiliary:compactDescriptors(index.auxiliary)};
if(JSON.stringify(expandLazyIndex(compactIndex))!==JSON.stringify(index))throw Error('Compact catalogue round-trip is not lossless.');
const compactName='data/lazy/index.compact.json';write(path.join(publicRoot,compactName),JSON.stringify(compactIndex)+'\n');generated.add(compactName);
const preload=`/* Generated initial catalogue only; full lessons load on demand. */\nwindow.MG_LAZY_INDEX=(${expandLazyIndex.toString()})(${serialize(compactIndex)});\nwindow.MG_DATA={catalog:window.MG_LAZY_INDEX.catalog,featured:window.MG_LAZY_INDEX.guidedIds.map(id=>window.MG_LAZY_INDEX.catalog.find(c=>c.id===id)),photos:window.MG_LAZY_INDEX.photos,sources:[],release:window.MG_LAZY_INDEX.release};\nwindow.MG_DATA_FILES=[];\n`;
new vm.Script(preload,{filename:'offline-data.js'});write(path.join(publicRoot,'offline-data.js'),preload);
for(const name of fs.readdirSync(publicRoot).filter(n=>/^offline-data-\d+\.js$/.test(n)))fs.unlinkSync(path.join(publicRoot,name));
// Remove superseded chunks only from the generated lazy directory.
for(const group of ['courses','resources','data'])for(const name of fs.readdirSync(path.join(lazyRoot,group)))if(!generated.has(`data/lazy/${group}/${name}`))fs.unlinkSync(path.join(lazyRoot,group,name));
// HTTP clients load the same ordered courses from bounded, immutable JSON
// parts. Keep featured.json as canonical authoring and portable-package data.
const hostedDir = path.join(publicRoot, 'data/course-parts');
fs.mkdirSync(hostedDir, { recursive: true });
const hostedParts = parts.map((courses, index) => {
  const content = JSON.stringify(courses) + '\n';
  const sha256 = hash(content), file = `part-${String(index + 1).padStart(4, '0')}-${sha256.slice(0,16)}.json`;
  const byteLength = Buffer.byteLength(content);
  if (byteLength > 7 * 1024 * 1024) throw new Error(`Hosted curriculum part ${index + 1} exceeds its budget.`);
  write(path.join(hostedDir, file), content);
  return { file, byteLength, sha256, courseCount: courses.length, courseIds: courses.map(course => course.id) };
});
const hostedManifest = { schemaVersion: 1, dataSet: 'featured', courseCount: data.featured.length, parts: hostedParts };
write(path.join(hostedDir, 'index.json'), JSON.stringify(hostedManifest, null, 2) + '\n');
const hostedFiles = new Set(['index.json', ...hostedParts.map(part => part.file)]);
for (const name of fs.readdirSync(hostedDir)) {
  if (/^part-\d{4}-[a-f0-9]{16}\.json$/.test(name) && !hostedFiles.has(name)) fs.unlinkSync(path.join(hostedDir, name));
}
for (const name of hostedFiles) generated.add(`data/course-parts/${name}`);
const outputs = Object.fromEntries([...generated].map(name => [relative(path.join(publicRoot, name)), hash(fs.readFileSync(path.join(publicRoot, name)))]));
write(manifestPath, JSON.stringify({ version: 1, dataSets: Object.keys(data), lazyVersion:1,initialBytes:Buffer.byteLength(preload),offlineParts:[], modules: [...modules.keys()], inputs: currentInputs, outputs }, null, 2) + '\n');
console.log(`Offline bundle built: ${modules.size} modules, ${Object.keys(data).length} data sets, ${data.featured.length} lazy guided courses; initial catalogue ${Buffer.byteLength(preload)} bytes. Compatibility parts: ${parts.length}.`);
