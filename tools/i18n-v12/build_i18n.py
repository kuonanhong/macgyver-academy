#!/usr/bin/env python3
"""Compile public/academy/i18n/<lang>.json into classic scripts i18n/<lang>.js
(loadable from https:// and from file:// offline packages)."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / 'public/academy/i18n'
count = 0
index = {}
for src in sorted(DIR.glob('*.json')):
    if src.name == 'index.json':
        continue
    d = json.loads(src.read_text('utf-8'))
    lang = d['lang']
    strings = dict(d['strings'])
    for delta in sorted((ROOT / 'tools/i18n-v12').glob(f'delta*/{lang}.json')):  # strings added after the main pass
        strings.update(json.loads(delta.read_text('utf-8')).get('strings', {}))
    payload = json.dumps({'lang': lang, 'name': d.get('name', lang), 'version': d.get('version', 12), 'strings': strings}, ensure_ascii=False, separators=(',', ':'))
    payload = payload.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    (DIR / f'{lang}.js').write_text(f'/* Generated by tools/i18n-v12/build_i18n.py — UI dictionary ({lang}). */\n(window.MG_I18N=window.MG_I18N||{{}})[{json.dumps(lang)}]={payload};\n', 'utf-8')
    index[lang] = {'name': d.get('name', lang), 'strings': len(strings)}
    count += 1
(DIR / 'index.json').write_text(json.dumps({'version': 12, 'languages': index}, ensure_ascii=False, indent=1) + '\n', 'utf-8')
print(f'{count} dictionaries compiled')
